import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const modules=new Map();
function bundle(file){
 file=path.resolve(file); const id=path.relative(root,file).replaceAll('\\','/');
 if(modules.has(id))return id;
 modules.set(id,''); let source=fs.readFileSync(file,'utf8'),names=[];
 source=source.replace(/^import\s+(.+?)\s+from\s+['"](.+?)['"];?\s*$/gm,(_,binding,spec)=>{
  const dep=bundle(path.resolve(path.dirname(file),spec.split('?')[0]));
  return binding.startsWith('* as ')?`const ${binding.slice(5)}=require(${JSON.stringify(dep)});`:`const ${binding}=require(${JSON.stringify(dep)});`;
 });
 source=source.replace(/^export \* from ['"](.+?)['"];?\s*$/gm,(_,spec)=>`Object.assign(exports,require(${JSON.stringify(bundle(path.resolve(path.dirname(file),spec.split('?')[0])))}));`);
 source=source.replace(/\bexport (function|const|let|class)\s+(\w+)/g,(_,type,name)=>{names.push(name);return `${type} ${name}`;});
 modules.set(id,source+`\nObject.assign(exports,{${names.join(',')}});`); return id;
}
const entry=bundle(path.join(root,'native/bridge.js'));
let out='// GENERATED by native/scripts/bundle-engine.mjs. Do not edit. No network or DOM.\n(function(){\n"use strict";\nif(typeof structuredClone!=="function")globalThis.structuredClone=x=>JSON.parse(JSON.stringify(x));\nconst factories={\n';
for(const[id,src]of modules)out+=`${JSON.stringify(id)}:function(exports,require){\n${src}\n},\n`;
out+=`};const cache={};function require(id){if(cache[id])return cache[id];const e={};cache[id]=e;factories[id](e,require);return e;}globalThis.Harbour=require(${JSON.stringify(entry)});})();\n`;
const target=path.join(root,'native/LittleHarbour/Resources/engine-bundle.js');
const manifest=Object.fromEntries([...modules.keys()].map(id=>[id,crypto.createHash('sha256').update(fs.readFileSync(path.join(root,id))).digest('hex')]));
const digest=JSON.stringify(manifest,null,2)+'\n';
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out||fs.readFileSync(target.replace('engine-bundle.js','engine-manifest.json'),'utf8')!==digest)throw Error('Native bundle is stale. Run node native/scripts/bundle-engine.mjs');}
else{fs.writeFileSync(target,out);fs.writeFileSync(target.replace('engine-bundle.js','engine-manifest.json'),digest);}
console.log(`Native engine: ${modules.size} source modules, ${out.length} bytes`);
