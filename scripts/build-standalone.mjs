import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const destination=process.argv[2]||path.resolve(root,'../Little-Harbour-Playtest-03.html');
let html=fs.readFileSync(path.join(root,'dist/index.html'),'utf8');
const image=fs.readFileSync(path.join(root,'dist/assets/harbour-map.png')).toString('base64');
const css=fs.readFileSync(path.join(root,'dist/style.css'),'utf8').replace("url('assets/harbour-map.png')","url('data:image/png;base64,"+image+"')");
const engine=fs.readFileSync(path.join(root,'dist/engine.js'),'utf8').replace(/^export /gm,'');
const scene=fs.readFileSync(path.join(root,'dist/scene.js'),'utf8').replace(/^export /gm,'');
const app=fs.readFileSync(path.join(root,'dist/app.js'),'utf8').replace(/^import .*\n/gm,'');
html=html.replace('<link rel="stylesheet" href="style.css">',()=>'<style>'+css+'</style>');
html=html.replace('<script type="module" src="app.js"></script>',()=>'<script>'+engine+'\n'+scene+'\n'+app+'</script>');
if(/(?:src|href)="https?:\/\//.test(html)||/@import/.test(html))throw new Error('External assets must not be present.');
fs.writeFileSync(destination,html);
console.log(destination);
